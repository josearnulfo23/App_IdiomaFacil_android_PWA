# ------------------------------------------------ generation / fill strategy
# Within a category we keep only unique (en) entries. If a category's real bank
# is shorter than its target, we top it up by cycling through a shuffled view of
# the WHOLE dictionary (every entry is a correct translation, so es != en always).
import random
random.seed(20260826)

# flatten to a pool of all real (en, es) pairs, de-duplicated by en
_all = {}
for _cat, _pairs in DICT.items():
    for _en, _es in _pairs:
        _all[_en] = _es
POOL = list(_all.items())  # list of (en, es), every one correctly translated

def fill_category(cat_id, target):
    base = DICT.get(cat_id, [])
    seen = set()
    out = []
    # first: category-specific real words, in declared order, de-duped
    for en, es in base:
        if en in seen:
            continue
        if es == en:  # identical loanword (e.g. "transistor") -> would show EN vs EN
            continue
        seen.add(en)
        out.append((en, es))
        if len(out) >= target:
            break
    # top up from the global real pool (never English fallback)
    if len(out) < target:
        pool = list(POOL)
        random.shuffle(pool)
        for en, es in pool:
            if en in seen:
                continue
            if es == en:
                continue
            seen.add(en)
            out.append((en, es))
            if len(out) >= target:
                break
    return out[:target]

